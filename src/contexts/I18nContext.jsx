const resolvePath = (source, path) => {
  if (!source || !path) return undefined;
  return path.split('.').reduce((acc, part) => {
    if (acc && typeof acc === 'object' && part in acc) {
      return acc[part];
    }
    return undefined;
  }, source);
};

const interpolate = (template, params = {}) => {
  if (typeof template !== 'string') return template;
  return Object.entries(params).reduce((result, [key, value]) => result.replaceAll(`{${key}}`, String(value)), template);
};

const I18nContext = createContext(null);

export const I18nProvider = ({ children }) => {
  const [language, setLanguage] = useState('en');

  useEffect(() => {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved && dictionaries[saved]) {
      setLanguage(saved);
      return;
    }

    const browserCode = window.navigator?.language?.slice(0, 2)?.toLowerCase();
    if (browserCode && dictionaries[browserCode]) {
      setLanguage(browserCode);
    }
  }, []);

  useEffect(() => {
    const locale = localeMap[language] || localeMap.en;
    const script = scriptMap[language] || scriptMap.en;
    document.documentElement.lang = locale;
    document.body.setAttribute('data-script', script);
    document.body.setAttribute('data-language', language);
  }, [language]);

  const setAppLanguage = (nextLanguage) => {
    if (!dictionaries[nextLanguage]) return;
    setLanguage(nextLanguage);
    localStorage.setItem(LANG_STORAGE_KEY, nextLanguage);
  };

  const t = useCallback(
    (key, fallback = '', params = {}) => {
      const active = dictionaries[language] || dictionaries.en;
      const activeValue = resolvePath(active, key);
      const englishValue = resolvePath(dictionaries.en, key);
      const base = activeValue ?? englishValue ?? fallback ?? key;

      if (import.meta.env.DEV && activeValue === undefined && !missingKeyWarnings.has(`${language}:${key}`)) {
        missingKeyWarnings.add(`${language}:${key}`);
        console.warn(`[i18n] Missing translation for "${key}" in language "${language}"`);
      }

      return interpolate(base, params);
    },
    [language],
  );

  const locale = localeMap[language] || localeMap.en;

  const formatNumber = useCallback(
    (value, options = {}) => new Intl.NumberFormat(locale, options).format(Number(value || 0)),
    [locale],
  );

  const formatCompactNumber = useCallback(
    (value, options = {}) =>
      new Intl.NumberFormat(locale, {
        notation: 'compact',
        maximumFractionDigits: 1,
        ...options,
      }).format(Number(value || 0)),
    [locale],
  );

  const formatPercent = useCallback(
    (value, options = {}) =>
      new Intl.NumberFormat(locale, {
        style: 'percent',
        minimumFractionDigits: 0,
        maximumFractionDigits: 0,
        ...options,
      }).format(Number(value || 0)),
    [locale],
  );

  const formatCurrencyINR = useCallback(
    (value, options = {}) =>
      new Intl.NumberFormat(locale, {
        style: 'currency',
        currency: 'INR',
        maximumFractionDigits: 0,
        ...options,
      }).format(Number(value || 0)),
    [locale],
  );

  const formatDate = useCallback(
    (value, options = {}) => new Intl.DateTimeFormat(locale, { dateStyle: 'medium', ...options }).format(new Date(value)),
    [locale],
  );

  const value = useMemo(
    () => ({
      language,
      locale,
      script: scriptMap[language] || scriptMap.en,
      setLanguage: setAppLanguage,
      t,
      formatNumber,
      formatCompactNumber,
      formatPercent,
      formatCurrencyINR,
      formatDate,
      languages: Object.entries(dictionaries).map(([code, data]) => ({ code, name: data.languageName })),
    }),
    [language, locale, t, formatNumber, formatCompactNumber, formatPercent, formatCurrencyINR, formatDate],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = () => {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used within I18nProvider');
  }

  return context;
};